#!/usr/bin/env python3
"""Generate config/widgets/adventureMapThor.json from the stock adventureMap.json:
the map view fills the whole top screen; every other widget still exists (the engine needs
the minimap, lists, info bar) but sits in a container that is never shown ("hideWhen": "always").
The Thor deck on the second screen replaces them."""
import json, os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def load(p):  # VCMI json allows comments + trailing commas
    t = open(p, encoding='utf-8').read()
    t = re.sub(r'("(?:\\.|[^"\\])*")|//[^\n]*|/\*.*?\*/', lambda m: m.group(1) or '', t, flags=re.S)
    return json.loads(re.sub(r',(\s*[}\]])', r'\1', t))


src = load(os.path.join(ROOT, 'config/widgets/adventureMap.json'))
full = {'left': 0, 'top': 0, 'right': 0, 'bottom': 0}
items = src['items']
view = [i for i in items if i.get('type') == 'adventureMapGameArea']
assert len(view) == 1
rest = [i for i in items if i is not view[0]]
out = {'options': src['options'], 'items': [
    dict(view[0], area=full),
    {'type': 'adventureMapContainer', 'name': 'thorHiddenSidebar', 'hideWhen': 'always', 'area': full, 'items': rest},
]}
dst = os.path.join(ROOT, 'config/widgets/adventureMapThor.json')
with open(dst, 'w', encoding='utf-8') as f:
    f.write('// generated by thor/gen_layout.py from adventureMap.json - do not edit\n')
    json.dump(out, f, indent='\t', ensure_ascii=False)
print(dst, len(rest), 'hidden items')
